# 1. Знакомство
print('Доброго времени суток')
# Спрашиваем у пол-ля имя 
user_name = input('Введите пожалуйста ваше имя ')
# Спрашиваем у пол-ля возраст
user_age = int(input('Введите пожалуйста ваш возраст '))

# 2. Сбор данных
# Спрашиваем у пол-ля его вес
user_weight = float(input('Введите пожалуйста вес '))
# Спрашиваем у пол-ля его рост 
user_height = float(input('Введите пожалуйста рост в метрах, например 1.8 '))


# 3. Логика расчетов (Функции как "черный ящик": используем арифметику)
# Формула ИМТ: вес разделить на (рост в квадрате)
bmi = round(user_weight / (user_height ** 2), 1)


# Подсчет воды: вес * 30 мл
water_per_kg = 30
water_ml = user_weight * water_per_kg
water_l = water_ml / 1000
# рассчитываем кол-во нормы воды
water_needed = round(water_l, 1)

# 4. Вывод красивого результата
print(f"Отчет для пользователя: {user_name} ({user_age})")
print(f"Твой Индекс Массы Тела: {bmi}")
print(f"Рекомендуемая норма воды: {water_needed} л. в день")
print("Расчет окончен. Будьте здоровы!")